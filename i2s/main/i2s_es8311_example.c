static void i2s_music(void *args)
{
    esp_err_t ret = ESP_OK;
    size_t bytes_write = 0;
    
    i2s_event_callbacks.on_sent = i2s_on_sent_cb;
    i2s_event_callbacks.on_send_q_ovf = i2s_send_q_ovf_cb;


    i2s_tx_ctx.start_ptr = (uint8_t *)sine_wave_pcm;
    i2s_tx_ctx.end_ptr = (uint8_t *)sine_wave_pcm + sizeof(sine_wave_pcm);
    
    //i2s_tx_ctx.start_ptr = (uint8_t *)music_pcm_start;
    //i2s_tx_ctx.end_ptr = (uint8_t *)music_pcm_end;

    i2s_tx_ctx.data_ptr = i2s_tx_ctx.start_ptr;

    i2s_channel_register_event_callback(tx_handle, &i2s_event_callbacks, &i2s_tx_ctx);

    // Disable TX channel and preload the data before enabling the TX channel,
    ESP_ERROR_CHECK(i2s_channel_preload_data(tx_handle, i2s_tx_ctx.data_ptr, i2s_tx_ctx.end_ptr - i2s_tx_ctx.data_ptr, &bytes_write));
    i2s_tx_ctx.data_ptr += bytes_write;  // Move forward the data pointer

    // Enable the TX channel
    ESP_ERROR_CHECK(i2s_channel_enable(tx_handle));
    vTaskSuspend(NULL);
}

