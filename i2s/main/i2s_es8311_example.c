static esp_err_t i2s_driver_init(void)
{
    i2s_chan_config_t chan_cfg = I2S_CHANNEL_DEFAULT_CONFIG(I2S_NUM, I2S_ROLE_MASTER);
    chan_cfg.auto_clear = true; // Auto clear the legacy data in the DMA buffer
    ESP_ERROR_CHECK(i2s_new_channel(&chan_cfg, &tx_handle, &rx_handle));
    i2s_std_config_t std_cfg = {
        .clk_cfg = I2S_STD_CLK_DEFAULT_CONFIG(EXAMPLE_SAMPLE_RATE),
        .slot_cfg = I2S_STD_PHILIPS_SLOT_DEFAULT_CONFIG(I2S_DATA_BIT_WIDTH_16BIT, I2S_SLOT_MODE_STEREO),
        .gpio_cfg = {
            .mclk = I2S_MCK_IO,
            .bclk = I2S_BCK_IO,
            .ws = I2S_WS_IO,
            .dout = I2S_DO_IO,
            .din = I2S_DI_IO,
            .invert_flags = {
                .mclk_inv = false,
                .bclk_inv = false,
                .ws_inv = false,
            },
        },
    };
    std_cfg.clk_cfg.mclk_multiple = EXAMPLE_MCLK_MULTIPLE;

    ESP_ERROR_CHECK(i2s_channel_init_std_mode(tx_handle, &std_cfg));
    ESP_ERROR_CHECK(i2s_channel_init_std_mode(rx_handle, &std_cfg));
    return ESP_OK;
}

static bool i2s_on_sent_cb(i2s_chan_handle_t handle, i2s_event_data_t *event, void *user_ctx)
{
    i2s_tx_context_t *ctx = (i2s_tx_context_t *)user_ctx;
    size_t bytes_written = 0;
    size_t bytes_remaining = ctx->end_ptr - ctx->data_ptr;

    // If no data left, reset pointer to the start of the PCM block.
    // This can happen if the song perfectly ends on a DMA block boundary.
    if (bytes_remaining == 0) {
        // We need to loop. Let's just reset the pointer for the next callback.
        ctx->data_ptr = ctx->start_ptr;
        bytes_remaining = ctx->end_ptr - ctx->data_ptr;
    }

    // Write the next chunk of data to the I2S driver
    esp_err_t ret = i2s_channel_write(handle,           // I2S channel handle
                                      ctx->data_ptr,    // Pointer to current position in the PCM data
                                      bytes_remaining,  // Max amount of data to write
                                      &bytes_written,   // How much was ACTUALLY written
                                      0);               // TIMEOUT MUST BE 0 - inside an ISR!
    
    if (bytes_written > 0) {
        ctx->data_ptr += bytes_written;
    }

    if ((ret != ESP_OK) && ret != ESP_ERR_TIMEOUT) {
        ESP_DRAM_LOGE(TAG, "I2S Write Error: %s", esp_err_to_name(ret));
    }

    return false;
}

