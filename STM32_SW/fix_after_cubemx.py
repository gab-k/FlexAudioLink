import os
import re
import sys
import shutil
from pathlib import Path


def restore_file(file_path, modified_content):
    """Write the modified content back to the file."""
    with open(file_path, 'w') as f:
        f.write(modified_content)
    print(f"Updated: {file_path}")

def process_cmake_file(file_path, context_name):
    """Process a CMake file with the given context name."""
    if not os.path.exists(file_path):
        print(f"Warning: {file_path} not found, skipping")
        return
        
    with open(file_path, 'r') as f:
        content = f.read()
    
    # Replace paths in the include directories
    content = re.sub(r'\$\{CMAKE_SOURCE_DIR\}/Core/', f'${{CMAKE_SOURCE_DIR}}/{context_name}/Core/', content)
    content = re.sub(r'\$\{CMAKE_SOURCE_DIR\}/\.\./', f'${{CMAKE_SOURCE_DIR}}/{context_name}/../', content)
    
    # Replace stm32cubemx library names
    content = re.sub(r'add_library\(stm32cubemx ', f'add_library(stm32cubemx_{context_name} ', content)
    content = re.sub(r'target_include_directories\(stm32cubemx ', f'target_include_directories(stm32cubemx_{context_name} ', content)
    content = re.sub(r'target_compile_definitions\(stm32cubemx ', f'target_compile_definitions(stm32cubemx_{context_name} ', content)
    content = re.sub(r'stm32cubemx\)', f'stm32cubemx_{context_name})', content)
    
    # Replace STM32_Drivers library names
    content = re.sub(r'add_library\(STM32_Drivers ', f'add_library(STM32_Drivers_{context_name} ', content)
    content = re.sub(r'target_sources\(STM32_Drivers ', f'target_sources(STM32_Drivers_{context_name} ', content)
    content = re.sub(r'target_link_libraries\(STM32_Drivers ', f'target_link_libraries(STM32_Drivers_{context_name} ', content)
    content = re.sub(r'set \(MX_LINK_LIBS \n    STM32_Drivers', f'set (MX_LINK_LIBS\n    STM32_Drivers_{context_name}', content)
        
    restore_file(file_path, content)

